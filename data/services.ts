// Helper functions for easy querying
export function getAllServices(): Service[] {
  return services;
}

export function getServiceBySlug(slug: string): Service | undefined {
  return services.find((s) => s.slug === slug || s.id === slug);
}

export function getSubService(serviceSlug: string, subSlug: string): { service: Service; subService: SubService } | undefined {
  const service = getServiceBySlug(serviceSlug);
  if (!service) return undefined;
  const subService = service.subServices.find((sub) => sub.slug === subSlug || sub.id === subSlug);
  if (!subService) return undefined;
  return { service, subService };
}

